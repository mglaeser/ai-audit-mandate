#!/usr/bin/env node
// Renders docs/check-index.md from the generated catalogue.
//
// A browsable index of all 119 checks, so a reader can find the one they need
// without paging through 390 KB of prose.
//
// Usage:
//   node scripts/build-check-index.mjs           # write docs/check-index.md
//   node scripts/build-check-index.mjs --check    # verify it is current (CI mode)

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(await readFile(join(root, 'catalogue/checks.json'), 'utf8'));

const VOLUME_PATH = {
  1: '../mandate/01-foundation-and-core-tracks.md',
  2: '../mandate/02-security-privacy-assurance.md',
};

const escape = (value) => value.replace(/\|/g, '\\|');

const marker = (check) => {
  const marks = [];
  if (check.stop_ship_class === 'direct') marks.push('**`STOP-SHIP`**');
  if (check.stop_ship_class === 'conditional') marks.push('`STOP-SHIP`*(cond.)*');
  if (check.has_structural_fix) marks.push('`S13`');
  return marks.join(' ') || '—';
};

const lines = [
  '<!-- Generated by scripts/build-check-index.mjs. Do not edit by hand. -->',
  '',
  '# Check index',
  '',
  `All ${catalogue.check_count} checks across ${catalogue.tracks.length} tracks, generated from the mandate prose.`,
  'Each check links to the volume that defines it.',
  '',
  '`S13` marks a check that carries a **structural fix** — the refactor that makes the defect',
  'unrepresentable rather than detectable. Where it appears, read it before the standing control.',
  '',
  '## At a glance',
  '',
  '| Track | Checks | Volume |',
  '| --- | --- | --- |',
];

for (const track of catalogue.tracks) {
  const part = track.id === 'C' ? 2 : 1;
  lines.push(
    `| **${track.id}** — ${track.name} | ${track.check_count} | [Volume ${part === 1 ? 'I' : 'II'}](${VOLUME_PATH[part]}) |`,
  );
}

lines.push(
  '',
  '| Band | Checks |',
  '| --- | --- |',
  ...Object.entries(catalogue.totals.by_band).map(([band, count]) => `| \`${band}\` | ${count} |`),
  '',
  `**Unconditional \`STOP-SHIP\`:** ${catalogue.totals.stop_ship_direct.map((id) => `\`${id}\``).join(', ')} — ` +
    'these hold `production_eligible` at `false` from Phase 0 onward.',
  '',
  `**Conditional \`STOP-SHIP\`:** ${catalogue.totals.stop_ship_conditional.map((id) => `\`${id}\``).join(', ')} — ` +
    'these escalate when their stated condition holds.',
  '',
  `**Carrying a structural fix:** ${catalogue.totals.with_structural_fix} of ${catalogue.check_count}.`,
  '',
);

for (const track of catalogue.tracks) {
  const checks = catalogue.checks.filter((check) => check.track === track.id);
  const part = checks[0].part;
  lines.push(
    `## Track ${track.id} — ${track.name}`,
    '',
    `${checks.length} checks · defined in [Volume ${part === 1 ? 'I' : 'II'}](${VOLUME_PATH[part]})`,
    '',
    '| ID | Check | Priority | Band | Notes |',
    '| --- | --- | --- | --- | --- |',
    ...checks.map(
      (check) =>
        `| \`${check.id}\` | ${escape(check.title)} | ${check.priority}/10 | \`${check.band}\` | ${marker(check)} |`,
    ),
    '',
  );
}

const serialised = `${lines.join('\n')}`;
const target = join(root, 'docs/check-index.md');

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => null);
  if (current !== serialised) {
    console.error('build-check-index: docs/check-index.md is stale — run `npm run docs`.');
    process.exit(1);
  }
  console.log('build-check-index: index is current.');
} else {
  await writeFile(target, serialised);
  console.log(`build-check-index: wrote index for ${catalogue.check_count} checks.`);
}
